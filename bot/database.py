"""SQLAlchemy ORM models and session management.

Defines the four core tables (trades, orders, signals, pnl_summary)
and provides a scoped-session factory for thread-safe DB access.
"""

from __future__ import annotations

import logging
from datetime import datetime, timezone
from typing import Optional

from sqlalchemy import (
    Column,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    String,
    create_engine,
    func,
)
from sqlalchemy.orm import (
    DeclarativeBase,
    Session,
    relationship,
    sessionmaker,
)

logger = logging.getLogger(__name__)


# ── Declarative Base ────────────────────────────────────────


class Base(DeclarativeBase):
    """Base class for all ORM models."""

    pass


# ── Models ──────────────────────────────────────────────────


class Trade(Base):
    """Represents a single trade lifecycle (entry → exit)."""

    __tablename__ = "trades"

    id: int = Column(Integer, primary_key=True, autoincrement=True)
    symbol: str = Column(String(50), nullable=False)
    side: str = Column(String(10), nullable=False)  # "buy" or "sell"
    entry_price: Optional[float] = Column(Float, nullable=True)
    exit_price: Optional[float] = Column(Float, nullable=True)
    qty: float = Column(Float, nullable=False)
    leverage: int = Column(Integer, nullable=False)
    pnl: Optional[float] = Column(Float, nullable=True)
    fees: float = Column(Float, nullable=True, default=0.0)
    status: str = Column(String(20), nullable=False, default="pending")
    entry_time: Optional[datetime] = Column(DateTime(timezone=True), nullable=True)
    exit_time: Optional[datetime] = Column(DateTime(timezone=True), nullable=True)
    exit_reason: Optional[str] = Column(String(50), nullable=True)
    sl_order_id: Optional[str] = Column(String(100), nullable=True)
    tp_order_id: Optional[str] = Column(String(100), nullable=True)

    orders = relationship("Order", back_populates="trade", lazy="selectin")

    def clear_exit_order_id(self, order_type: str) -> None:
        """Clear the cached SL or TP exchange order ID on this trade.

        Args:
            order_type: ``"stop_loss"`` or ``"take_profit"``.
        """
        if order_type == "stop_loss":
            self.sl_order_id = None
        elif order_type == "take_profit":
            self.tp_order_id = None

    def __repr__(self) -> str:
        return (
            f"<Trade(id={self.id}, symbol={self.symbol}, side={self.side}, "
            f"status={self.status}, pnl={self.pnl})>"
        )


class Order(Base):
    """Represents an individual exchange order linked to a trade."""

    __tablename__ = "orders"

    id: int = Column(Integer, primary_key=True, autoincrement=True)
    trade_id: Optional[int] = Column(Integer, ForeignKey("trades.id"), nullable=True)
    exchange_order_id: Optional[str] = Column(String(100), nullable=True)
    type: str = Column(String(20), nullable=False)  # "limit", "stop_limit"
    side: str = Column(String(10), nullable=False)   # "buy" or "sell"
    price: float = Column(Float, nullable=False)
    qty: float = Column(Float, nullable=False)
    status: str = Column(String(20), nullable=False, default="pending")
    created_at: datetime = Column(
        DateTime(timezone=True), server_default=func.now()
    )
    updated_at: datetime = Column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )

    trade = relationship("Trade", back_populates="orders")

    def __repr__(self) -> str:
        return (
            f"<Order(id={self.id}, exchange_id={self.exchange_order_id}, "
            f"type={self.type}, side={self.side}, status={self.status})>"
        )


class Signal(Base):
    """Stores every signal generated by the strategy for audit."""

    __tablename__ = "signals"

    id: int = Column(Integer, primary_key=True, autoincrement=True)
    symbol: str = Column(String(50), nullable=False)
    timeframe: str = Column(String(10), nullable=False)
    signal_type: str = Column(String(10), nullable=False)  # "buy" or "sell"
    ema_fast: float = Column(Float, nullable=False)
    ema_slow: float = Column(Float, nullable=False)
    rsi: float = Column(Float, nullable=False)
    price: float = Column(Float, nullable=False)
    timestamp: datetime = Column(
        DateTime(timezone=True), server_default=func.now()
    )

    def __repr__(self) -> str:
        return (
            f"<Signal(id={self.id}, signal_type={self.signal_type}, "
            f"price={self.price}, rsi={self.rsi})>"
        )


class PnlSummary(Base):
    """Periodic PnL summary snapshot (generated every 6 hours)."""

    __tablename__ = "pnl_summary"

    id: int = Column(Integer, primary_key=True, autoincrement=True)
    period_start: datetime = Column(DateTime(timezone=True), nullable=False)
    period_end: datetime = Column(DateTime(timezone=True), nullable=False)
    total_trades: int = Column(Integer, nullable=False, default=0)
    wins: int = Column(Integer, nullable=False, default=0)
    losses: int = Column(Integer, nullable=False, default=0)
    gross_pnl: float = Column(Float, nullable=False, default=0.0)
    net_pnl: float = Column(Float, nullable=False, default=0.0)
    fees_paid: float = Column(Float, nullable=False, default=0.0)
    generated_at: datetime = Column(
        DateTime(timezone=True), server_default=func.now()
    )

    def __repr__(self) -> str:
        return (
            f"<PnlSummary(id={self.id}, trades={self.total_trades}, "
            f"net_pnl={self.net_pnl})>"
        )


# ── Engine & Session Factory ───────────────────────────────


_engine = None
_SessionFactory = None


def init_db(database_url: str) -> None:
    """Initialise the database engine and session factory.

    Args:
        database_url: PostgreSQL connection string.
    """
    global _engine, _SessionFactory
    _engine = create_engine(
        database_url,
        pool_size=5,
        max_overflow=10,
        pool_pre_ping=True,
        echo=False,
    )
    _SessionFactory = sessionmaker(bind=_engine, expire_on_commit=False)
    logger.info("Database engine initialised: %s", database_url.split("@")[-1])


def get_session() -> Session:
    """Return a new SQLAlchemy session.

    Raises:
        RuntimeError: If init_db() has not been called.
    """
    if _SessionFactory is None:
        raise RuntimeError("Database not initialised — call init_db() first.")
    return _SessionFactory()


def create_tables() -> None:
    """Create all tables (used only for quick testing outside Alembic)."""
    if _engine is None:
        raise RuntimeError("Database not initialised — call init_db() first.")
    Base.metadata.create_all(_engine)
    logger.info("All tables created (if not already present).")
